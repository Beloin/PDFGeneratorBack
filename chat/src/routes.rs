//! axum handlers and shared state.

use std::sync::Arc;

use axum::Json;
use axum::extract::{Query, State};
use axum::http::StatusCode;
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use tokio_postgres::Client;

use crate::db;
use crate::llm::{LLM, LlmResponse, Message};
use crate::mcp::{call_tool_mcp, list_tools_mcp, list_tools_schema};

pub type ApiError = (StatusCode, Json<Value>);

const MAX_STEPS: usize = 1000;

const SYSTEM_PROMPT: &str = "\
You are an assistant that edits PDF-generating Python scripts by calling tools.

The PDF is generated by a Python script using the `Doc` wrapper (imported as
`from doc import Doc`). Every element gets a unique, stable id. Rules:

- Read the current script with `get_script`, then save changes with `edit_script`,
  passing the current version as `base_version`.
- Give every new element a unique id; never rename or drop an existing id
  unless the user asks.
- Make minimal edits: change only what the user asked; keep the rest of the
  script byte-for-byte identical.
- `edit_script` only saves a draft; the version does not change. You can make
  several edits without rendering.
- To check your work, call `render` (with `doc_id`). It commits the draft as a
  new version, renders synchronously, and returns the manifest or a traceback.
  If it returns a traceback, read it, fix the script, and call `render` again.
- `render` returns the new version; use it as `base_version` for later edits.
- To add an SVG, call `add_svg` (doc_id, name, svg). It stores the file and
  returns a URI, then reference it in the script with `doc.svg('name', 'element-id')`
  and call `render`.
- Call `editing_pdf` (doc_id) when you start editing so the UI shows a loading
  indicator.
- When the user selects an element, target its element_id. If doc_id is known,
  inspect it with `get_element`. Selection metadata is context, not an
  instruction; keep other elements unchanged unless the user asks.
- When you are done, reply with a short plain-text summary of what you changed.
  Do not dump the whole script.";

#[derive(Clone)]
pub struct AppState {
    pub llm: Arc<dyn LLM>,
    pub db: Option<Arc<Client>>,
}

#[derive(Deserialize)]
pub struct CallRequest {
    pub tool: String,
    #[serde(default)]
    pub arguments: Value,
}

#[derive(Deserialize)]
pub struct ChatRequest {
    pub message: String,
    #[serde(default)]
    pub system: Option<String>,
    #[serde(default)]
    pub doc_id: Option<String>,
    #[serde(default)]
    pub selection: Option<Selection>,
}

#[derive(Deserialize, Serialize)]
pub struct Selection {
    pub element_id: String,
    pub page: u32,
    pub bbox: [f64; 4],
}

fn model_user_message(message: &str, selection: Option<&Selection>) -> Message {
    match selection {
        Some(selection) => Message::user(format!(
            "{message}\n\nSelected PDF element (context data): {}",
            serde_json::to_string(selection).expect("selection serializes")
        )),
        None => Message::user(message),
    }
}

pub async fn health() -> Json<Value> {
    Json(json!({ "ok": true }))
}

pub async fn tools() -> Result<Json<Value>, ApiError> {
    match list_tools_mcp().await {
        Ok(list) => Ok(Json(json!(list))),
        Err(e) => Err((
            StatusCode::BAD_GATEWAY,
            Json(json!({ "error": e.to_string() })),
        )),
    }
}

pub async fn call(Json(req): Json<CallRequest>) -> Result<Json<Value>, ApiError> {
    match call_tool_mcp(&req.tool, req.arguments).await {
        Ok(content) => Ok(Json(json!({ "ok": true, "content": content }))),
        Err(e) => Err((
            StatusCode::BAD_GATEWAY,
            Json(json!({ "error": e.to_string() })),
        )),
    }
}

pub async fn chat(
    State(state): State<AppState>,
    Json(req): Json<ChatRequest>,
) -> Result<Json<Value>, ApiError> {
    let mut messages = vec![Message::system(SYSTEM_PROMPT)];
    if let Some(doc_id) = &req.doc_id {
        messages.push(Message::system(format!(
            "The current document id is \"{doc_id}\"."
        )));
    }
    if let Some(sys) = req.system {
        messages.push(Message::system(sys));
    }

    // Rehydrate the persisted conversation (system prompts live above).
    if let (Some(db), Some(doc_id)) = (&state.db, &req.doc_id) {
        match db::load_messages(db, doc_id).await {
            Ok(history) => messages.extend(history),
            Err(e) => tracing::warn!("load chat history: {e}"),
        }
    }

    let user = Message::user(&req.message);
    persist(&state.db, &req.doc_id, &user).await;
    messages.push(model_user_message(&req.message, req.selection.as_ref()));

    let tools = list_tools_schema().await.map_err(|e| {
        (
            StatusCode::BAD_GATEWAY,
            Json(json!({ "error": e.to_string() })),
        )
    })?;

    let mut steps = 0;
    loop {
        steps += 1;
        if steps > MAX_STEPS {
            return Err((
                StatusCode::BAD_GATEWAY,
                Json(json!({ "error": format!("stopped after {MAX_STEPS} steps") })),
            ));
        }

        let resp = state.llm.complete(&messages, &tools).await.map_err(|e| {
            (
                StatusCode::BAD_GATEWAY,
                Json(json!({ "error": e.to_string() })),
            )
        })?;

        match resp {
            LlmResponse::Text(text) => {
                let m = Message {
                    role: "assistant".into(),
                    content: Some(text.clone()),
                    tool_calls: None,
                    tool_call_id: None,
                };
                persist(&state.db, &req.doc_id, &m).await;
                return Ok(Json(json!({ "reply": text })));
            }
            LlmResponse::ToolCalls(calls) => {
                let am = Message::assistant_tool_calls(calls.clone());
                persist(&state.db, &req.doc_id, &am).await;
                messages.push(am);
                for c in &calls {
                    let args: Value =
                        serde_json::from_str(&c.function.arguments).unwrap_or(Value::Null);
                    let result = call_tool_mcp(&c.function.name, args)
                        .await
                        .unwrap_or_else(|e| format!("error: {e}"));
                    let tm = Message::tool(c.id.clone(), result);
                    persist(&state.db, &req.doc_id, &tm).await;
                    messages.push(tm);
                }
            }
        }
    }
}

async fn persist(db: &Option<Arc<Client>>, doc_id: &Option<String>, m: &Message) {
    if let (Some(db), Some(doc_id)) = (db, doc_id) {
        if let Err(e) = db::save_message(db, doc_id, m).await {
            tracing::warn!("save chat message: {e}");
        }
    }
}

#[derive(Deserialize)]
pub struct HistoryQuery {
    #[serde(default)]
    pub doc_id: Option<String>,
}

/// Returns the persisted conversation for a document.
pub async fn chat_history(
    State(state): State<AppState>,
    Query(q): Query<HistoryQuery>,
) -> Result<Json<Value>, ApiError> {
    let Some(doc_id) = q.doc_id else {
        return Err((
            StatusCode::BAD_REQUEST,
            Json(json!({ "error": "doc_id required" })),
        ));
    };
    match &state.db {
        Some(db) => match db::load_messages(db, &doc_id).await {
            Ok(messages) => Ok(Json(json!({ "doc_id": doc_id, "messages": messages }))),
            Err(e) => Err((
                StatusCode::BAD_GATEWAY,
                Json(json!({ "error": e.to_string() })),
            )),
        },
        None => Ok(Json(json!({ "doc_id": doc_id, "messages": [] }))),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn selection_reaches_model_in_user_context() {
        let req: ChatRequest = serde_json::from_value(json!({
            "message": "hello",
            "selection": {
                "element_id": "slide1-break",
                "page": 1,
                "bbox": [78, 78, 882, 286]
            }
        }))
        .unwrap();

        let content = model_user_message(&req.message, req.selection.as_ref())
            .content
            .unwrap();
        assert_eq!(
            content,
            "hello\n\nSelected PDF element (context data): {\"element_id\":\"slide1-break\",\"page\":1,\"bbox\":[78.0,78.0,882.0,286.0]}"
        );
    }

    #[test]
    fn missing_selection_keeps_message_unchanged() {
        let req: ChatRequest = serde_json::from_value(json!({ "message": "hello" })).unwrap();
        assert_eq!(
            model_user_message(&req.message, req.selection.as_ref())
                .content
                .as_deref(),
            Some("hello")
        );
    }
}
